// Regenerates /data/DATA-NEEDED.md from the clinic JSONs (CLAUDE.md rule 1).
// Runs automatically before every build (npm run build). Never edit the
// output by hand; supply data via intake/research and update the clinic JSON.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const CLINICS_DIR = 'data/clinics';
const OUT = 'data/DATA-NEEDED.md';

// Who can supply each field (mirrors the two intake instruments).
const SOURCE = {
  display_name: 'client', doctor_name: 'client', qualifications: 'client',
  council_reg_no: 'client', years_experience: 'client', bio: 'client',
  services: 'client', fees: 'client', phone_e164: 'client', whatsapp: 'client',
  email: 'client', languages: 'client', usp: 'client', logo: 'client',
  headshot: 'client', interior_photos: 'client',
  address_full: 'web', sector: 'web', city: 'web', pincode: 'web',
  lat: 'web', lng: 'web', place_id: 'web', maps_embed_url: 'web',
  hours: 'web', existing_url: 'web', existing_url_status: 'web',
  gbp_url: 'web', rating: 'web', reviews: 'web',
  primary_keyword: 'pipeline (6b)', secondary_keywords: 'pipeline (6b)',
  meta_title: 'pipeline (6b)', meta_description: 'pipeline (6b)',
};

const BLOCKING = new Set(['display_name', 'address_full', 'services']);
const CONTACT = ['phone_e164', 'whatsapp', 'email'];

// '-reference' stubs exist only to prove templates render (rule 5); their
// gaps are not chase-able data, so they stay out of this log.
const files = (await readdir(CLINICS_DIR))
  .filter((f) => f.endsWith('.json') && !f.startsWith('_') && !f.endsWith('-reference.json'))
  .sort();
const today = new Date().toISOString().slice(0, 10);

let out = `# DATA-NEEDED — outstanding clinic data gaps

Auto-regenerated by \`npm run gen:data-needed\` on ${today}. Do not edit by
hand; supply the data via the intake form (client) or research instrument
(web) and update the clinic JSON.

`;

let totalRows = 0;
for (const f of files) {
  const clinic = JSON.parse(await readFile(path.join(CLINICS_DIR, f), 'utf8'));
  const status = clinic.data_status ?? {};
  const missing = Object.keys(status).filter((k) => status[k] === 'missing');
  if (missing.length === 0) continue;

  const noContact = CONTACT.every((c) => status[c] === 'missing');
  out += `## ${clinic.display_name ?? clinic.slug} (\`${clinic.slug}\`, ${clinic.block_id})\n\n`;
  out += `| field | build-blocking? | supply via |\n|---|---|---|\n`;
  for (const field of missing) {
    const blocking = BLOCKING.has(field) || (noContact && CONTACT.includes(field));
    out += `| ${field} | ${blocking ? '**yes**' : 'no'} | ${SOURCE[field] ?? 'client'} |\n`;
    totalRows += 1;
  }
  out += '\n';
}

if (totalRows === 0) out += '_No outstanding gaps._\n';
await writeFile(OUT, out);
console.log(`DATA-NEEDED.md regenerated: ${totalRows} gap rows across ${files.length} clinic(s).`);
